@dataclass(frozen=True)
class _ModuleParts:
    """One source module split into hoistable imports and remaining body text."""

    plain_imports: frozenset[str]
    from_imports: dict[str, frozenset[str]]
    future_names: frozenset[str]
    body: str


def _module_docstring_node(tree: ast.Module) -> ast.Expr | None:
    if not tree.body:
        return None
    first = tree.body[0]
    if (
        isinstance(first, ast.Expr)
        and isinstance(first.value, ast.Constant)
        and isinstance(first.value.value, str)
    ):
        return first
    return None


def _is_internal_import(node: ast.ImportFrom) -> bool:
    """True for a relative import or one rooted at ``underwrite_core`` -- these
    name modules that are being inlined into this same file, so they are
    dropped rather than hoisted (the merged file imports
    nothing starting with ``underwrite``)."""
    if node.level > 0:
        return True
    return node.module is not None and node.module.split(".")[0] == "underwrite_core"


def _alias_name(alias: ast.alias) -> str:
    return alias.name if alias.asname is None else f"{alias.name} as {alias.asname}"


def _line_range(node: ast.stmt) -> range:
    end = node.end_lineno if node.end_lineno is not None else node.lineno
    return range(node.lineno, end + 1)


def _collect_import(
    stmt: ast.Import | ast.ImportFrom,
    plain_imports: set[str],
    from_imports: dict[str, set[str]],
    future_names: set[str],
) -> None:
    if isinstance(stmt, ast.Import):
        plain_imports.update(_alias_name(alias) for alias in stmt.names)
        return
    if _is_internal_import(stmt):
        return
    names = {_alias_name(alias) for alias in stmt.names}
    if stmt.module == "__future__":
        future_names.update(names)
    elif stmt.module is not None:
        from_imports.setdefault(stmt.module, set()).update(names)


def _parse_module(source: str) -> _ModuleParts:
    """Split ``source`` into (hoistable imports, remaining body text).

    Only top-level statements are inspected -- an import nested inside a
    function/class/if-block would be left untouched inside the body text,
    not hoisted (see the module docstring's "Assumes" paragraph; none of
    canonical.py/chain.py/bundle.py do this today)."""
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    skip_lines: set[int] = set()

    docstring_node = _module_docstring_node(tree)
    if docstring_node is not None:
        skip_lines.update(_line_range(docstring_node))

    plain_imports: set[str] = set()
    from_imports: dict[str, set[str]] = {}
    future_names: set[str] = set()
    for stmt in tree.body:
        if isinstance(stmt, (ast.Import, ast.ImportFrom)):
            skip_lines.update(_line_range(stmt))
            _collect_import(stmt, plain_imports, from_imports, future_names)

    body_lines = [line for lineno, line in enumerate(lines, start=1) if lineno not in skip_lines]
    body = "".join(body_lines).strip("\n")
    return _ModuleParts(
        plain_imports=frozenset(plain_imports),
        from_imports={module: frozenset(names) for module, names in from_imports.items()},
        future_names=frozenset(future_names),
        body=body,
    )


def _merge_imports(parts: list[_ModuleParts]) -> str:
    """Hoist and de-duplicate every part's imports into one block: a future
    import line (if any) first, then plain ``import x`` lines, then
    ``from x import...`` lines -- each group sorted for determinism."""
    plain: set[str] = set()
    from_map: dict[str, set[str]] = {}
    future: set[str] = set()
    for part in parts:
        plain |= part.plain_imports
        future |= part.future_names
        for module, names in part.from_imports.items():
            from_map.setdefault(module, set()).update(names)

    lines: list[str] = []
    if future:
        lines.append(f"from __future__ import {', '.join(sorted(future))}")
        lines.append("")
    lines.extend(f"import {name}" for name in sorted(plain))
    lines.extend(
        f"from {module} import {', '.join(sorted(names))}"
        for module, names in sorted(from_map.items())
    )
    return "\n".join(lines)


def _render_source_digests(digests: dict[str, str]) -> str:
    entries = ",\n".join(f'    "{name}": "{digests[name]}"' for name in _CORE_MODULES)
    return f"SOURCE_DIGESTS: Final[dict[str, str]] = {{\n{entries},\n}}"


def _marked_section(label: str, body: str) -> str:
    marker = f"# --- {label} " + "-" * max(4, 76 - len(label))
    return f"{marker}\n{body}"


def build_verify_source(core_root: Path) -> bytes:
    """Assemble the full ``verify.py`` source, deterministically, from the
    three source modules under ``core_root/src/underwrite_core`` plus the
    fixed ``_CLI_SOURCE`` template."""
    src_dir = core_root / "src" / "underwrite_core"
    digests: dict[str, str] = {}
    parsed: dict[str, _ModuleParts] = {}
    for name in _CORE_MODULES:
        text = (src_dir / name).read_text(encoding="utf-8")
        digests[name] = "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()
        parsed[name] = _parse_module(text)

    cli_parts = _parse_module(_CLI_SOURCE)
    imports_block = _merge_imports([*(parsed[name] for name in _CORE_MODULES), cli_parts])
    digests_block = _render_source_digests(digests)
    module_sections = [_marked_section(name, parsed[name].body) for name in _CORE_MODULES]
    cli_section = _marked_section("CLI", cli_parts.body)

    head = "\n\n\n".join([_HEADER_COMMENT, _MODULE_DOCSTRING, imports_block])
    # Exactly one blank line between the hoisted import block and the first
    # statement after it -- ruff/isort's I001 formatting expectation (every
    # OTHER section boundary below uses two, PEP8's top-level spacing).
    tail = "\n\n\n".join([digests_block, *module_sections, cli_section])
    return (head + "\n\n" + tail + "\n").encode("utf-8")


def _default_core_root() -> Path:
    return Path(__file__).resolve().parent.parent


def _default_output_path() -> Path:
    return Path(__file__).resolve().parent / "verify.py"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate build/verify.py from underwrite_core."
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Output path (default: verify.py next to this script).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit 1 if the generated bytes differ from --out.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    target: Path = args.out if args.out is not None else _default_output_path()
    generated = build_verify_source(_default_core_root())

    if args.check:
        if not target.exists() or target.read_bytes() != generated:
            print(f"gen_verify: DRIFT: {target} does not match generated output", file=sys.stderr)
            return 1
        print(f"gen_verify: OK ({target}, {len(generated)} bytes, no drift)")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(generated)
    print(f"gen_verify: wrote {target} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
